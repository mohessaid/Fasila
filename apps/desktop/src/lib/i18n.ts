const DICTS: Record<Lang, Dict> = { en, ar, fr };

export function resolveLang(pref: string): Lang {
  if (pref === "en" || pref === "ar" || pref === "fr") return pref;
  const nav = (navigator.language || "en").slice(0, 2);
  return nav === "ar" ? "ar" : nav === "fr" ? "fr" : "en";
}

export function dict(lang: Lang): Dict {
  return DICTS[lang];
}
